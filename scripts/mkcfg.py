"""Generate encoder-specific ABMIL configs from configs/abmil.yaml.

Copies everything (so the comparison with the r50 baseline stays fair) and changes only
the input dimension, which is what src/train.py reads from data.in_dim.

Usage:  .\\venv\\Scripts\\python.exe scripts\\mkcfg.py
"""
import sys
from pathlib import Path

import yaml

BASE = Path("configs/abmil.yaml")
TARGETS = {"chief": 768, "gigap": 1536, "uni": 1024}

if not BASE.exists():
    sys.exit(f"ERROR: {BASE} not found (run from the repo root)")

base = yaml.safe_load(BASE.read_text(encoding="utf-8")) or {}
for enc, dim in TARGETS.items():
    cfg = {k: (dict(v) if isinstance(v, dict) else v) for k, v in base.items()}
    cfg.setdefault("model", {})["in_dim"] = dim
    cfg.setdefault("data", {})["in_dim"] = dim
    header = (
        f"# ABMIL on {enc.upper()} features (D = {dim}).\n"
        f"# Generated by scripts/mkcfg.py from configs/abmil.yaml; only in_dim differs,\n"
        f"# so the hyperparameters are identical to the r50 baseline.\n\n"
    )
    out = Path(f"configs/abmil_{enc}.yaml")
    out.write_text(header + yaml.safe_dump(cfg, sort_keys=False), encoding="utf-8")
    reloaded = yaml.safe_load(out.read_text(encoding="utf-8"))
    ok = (reloaded["model"]["in_dim"] == dim and reloaded["data"]["in_dim"] == dim)
    print(f"{out}: model.in_dim={reloaded['model']['in_dim']} data.in_dim={reloaded['data']['in_dim']} "
          f"lr={reloaded['training']['lr']} epochs={reloaded['training']['max_epochs']} -> {'OK' if ok else 'BAD'}")