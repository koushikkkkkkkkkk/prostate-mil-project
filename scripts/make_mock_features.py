"""Generate a tiny SYNTHETIC PANDA-shaped dataset for development.

Why this exists
---------------
Nobody should wait for the real PANDA download + tiling + feature extraction to
build and debug the training / evaluation / heatmap code. This script fabricates
slides that obey exactly the same file contract:

    data/mock/manifest.csv                 image_id, data_provider, isup_grade, gleason_score, split
    data/mock/features/{image_id}.pt       {"features": [N, D], "coords": [N, 2], "patch_paths": [N]}
    data/mock/thumbnails/{image_id}.png    low-res "slide"
    data/mock/masks/{image_id}.png         bright = "tumour" (for overlap scoring)
    data/mock/patches/{image_id}/*.png     small RGB tiles (for top-k patch figures)

The synthetic signal is deliberately learnable: patches inside the "tumour"
region get a class-dependent offset in feature space, so a correct pipeline
shows QWK > 0 and heatmaps that overlap the mask. That makes the mock data a
good *smoke test* and a completely invalid *result*. Every generated README and
results folder says so.

Usage::

    python scripts/make_mock_features.py --out-dir data/mock --seed 7
"""

from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path
from typing import Any, Dict, List, Tuple

import numpy as np
import torch
from PIL import Image, ImageDraw, ImageFilter

SPLIT_COUNTS = {"train": 18, "val": 6, "test": 6}
PROVIDERS = ("karolinska", "radboud")
GLEASON = {
    0: "negative",
    1: "3+3",
    2: "3+4",
    3: "4+3",
    4: "4+4",
    5: "5+5",
}
DISCLAIMER = (
    "SYNTHETIC MOCK DATA -- DO NOT REPORT.\n\n"
    "Every file in this folder was generated by scripts/make_mock_features.py to\n"
    "test the MIL pipeline plumbing (shapes, loaders, training loop, heatmaps).\n"
    "The images are coloured noise and the features are random numbers with an\n"
    "injected class offset. Any QWK / accuracy / heatmap from this data says\n"
    "nothing about PANDA performance and must never appear in the report, slides\n"
    "or demo.\n\n"
    "How to read the mock numbers:\n"
    "  * a correct pipeline should reach clearly-better-than-chance QWK on the\n"
    "    mock test split (the class signal is deliberately learnable);\n"
    "  * the attention-vs-mask lift may sit near 1.0, because the synthetic class\n"
    "    signal is spread over every tumour patch, so uniform attention is enough.\n"
    "    That is a property of the fake data, not of CLAM-SB.\n"
)


def _make_thumbnail(
    rng: np.random.Generator, width: int, height: int, grade: int
) -> Tuple[Image.Image, np.ndarray]:
    """Blurred blobs on a pale background; the mask marks the darker tissue."""
    image = Image.new("RGB", (width, height), (240, 235, 230))
    draw = ImageDraw.Draw(image)

    # Background tissue (benign) blobs.
    for _ in range(14):
        cx, cy = rng.integers(0, width), rng.integers(0, height)
        radius = int(rng.integers(width // 12, width // 5))
        colour = tuple(int(c) for c in rng.integers(150, 205, size=3))
        draw.ellipse([cx - radius, cy - radius, cx + radius, cy + radius], fill=colour)

    # "Tumour" region: more, darker blobs, larger for higher grades.
    mask = np.zeros((height, width), dtype=np.uint8)
    n_tumour = 3 + 2 * grade
    for _ in range(n_tumour):
        cx, cy = rng.integers(width // 6, max(width // 6 + 1, width - width // 6)), rng.integers(
            height // 6, max(height // 6 + 1, height - height // 6)
        )
        radius = int(rng.integers(width // 14, width // 8) * (1.0 + 0.15 * grade))
        colour = tuple(int(c) for c in rng.integers(80, 145, size=3))
        draw.ellipse([cx - radius, cy - radius, cx + radius, cy + radius], fill=colour)
        draw.ellipse(
            [cx - radius, cy - radius, cx + radius, cy + radius],
            outline=(70, 40, 70),
            width=2,
        )

    image = image.filter(ImageFilter.GaussianBlur(radius=1.2))
    array = np.asarray(image, dtype=np.uint8).astype(np.int16)
    # Mask = darker-than-median pixels (the dark "tumour" blobs dominate there).
    gray = array.mean(axis=2)
    mask = (gray < np.median(gray) - 8).astype(np.uint8) * 255
    return image, mask


def _make_slide(
    out_dir: Path,
    image_id: str,
    grade: int,
    rng: np.random.Generator,
    feature_dim: int,
    grid_cols: int,
    grid_rows: int,
    patch_size: int,
    thumbnail_width: int,
    patch_px: int,
    tissue_fraction_target: float,
    signal_strength: float,
    nuisance_strength: float,
) -> Dict[str, Any]:
    thumbnail_h = int(round(thumbnail_width * grid_rows / grid_cols))
    thumbnail, mask = _make_thumbnail(rng, thumbnail_width, thumbnail_h, grade)

    thumb_dir = out_dir / "thumbnails"
    mask_dir = out_dir / "masks"
    patch_dir = out_dir / "patches" / image_id
    features_dir = out_dir / "features"
    for directory in (thumb_dir, mask_dir, patch_dir, features_dir):
        directory.mkdir(parents=True, exist_ok=True)

    thumbnail.save(thumb_dir / f"{image_id}.png")
    Image.fromarray(mask, mode="L").save(mask_dir / f"{image_id}.png")

    slide_w = grid_cols * patch_size
    slide_h = grid_rows * patch_size
    scale_x = thumbnail_width / slide_w
    scale_y = thumbnail_h / slide_h

    coords: List[List[int]] = []
    patch_paths: List[str] = []
    tumour_flags: List[int] = []

    mask_image = Image.fromarray(mask, mode="L")
    for row in range(grid_rows):
        for col in range(grid_cols):
            x, y = col * patch_size, row * patch_size
            # Keep a tissue-like subset so N varies per slide (like real data).
            if rng.random() > tissue_fraction_target:
                continue
            box = (
                int(x * scale_x),
                int(y * scale_y),
                max(int((x + patch_size) * scale_x), int(x * scale_x) + 1),
                max(int((y + patch_size) * scale_y), int(y * scale_y) + 1),
            )
            patch = thumbnail.crop(box).resize((patch_px, patch_px))
            patch_path = patch_dir / f"{image_id}_x{x}_y{y}.png"
            patch.save(patch_path)

            mask_patch = np.asarray(mask_image.crop(box), dtype=np.uint8)
            tumour = int((mask_patch > 127).mean() > 0.3)

            coords.append([x, y])
            patch_paths.append(str(patch_path))
            tumour_flags.append(tumour)

    if not coords:
        raise RuntimeError(f"Mock slide {image_id} produced no patches")

    n = len(coords)
    features = rng.normal(size=(n, feature_dim)).astype(np.float32)
    direction = np.zeros(feature_dim, dtype=np.float32)
    direction[grade % feature_dim] = 1.0
    direction[(grade * 53 + 17) % feature_dim] = 0.6
    tumour_flags_array = np.asarray(tumour_flags, dtype=bool)
    # Class signal lives in the "tumour" patches only: a correct model therefore
    # *should* attend to them, which is what the heatmap/overlap plumbing checks.
    features[tumour_flags_array] += signal_strength * (1.0 + 0.25 * grade) * direction

    # Slide-level nuisance direction shared by *all* patches. Because it is much
    # larger than the class signal, mean-pooling is dominated by noise and a
    # working attention model has to learn to focus on the signal patches -- the
    # same reason MIL pooling exists in the first place.
    nuisance = rng.normal(size=feature_dim).astype(np.float32)
    nuisance /= max(float(np.linalg.norm(nuisance)), 1e-8)
    features += nuisance_strength * nuisance

    torch.save(
        {
            "features": torch.from_numpy(features),
            "coords": torch.tensor(coords, dtype=torch.float32),
            "patch_paths": patch_paths,
            "tumour_flags": torch.tensor(tumour_flags),
        },
        features_dir / f"{image_id}.pt",
    )

    return {
        "image_id": image_id,
        "data_provider": PROVIDERS[int(rng.integers(0, len(PROVIDERS)))],
        "isup_grade": grade,
        "gleason_score": GLEASON[grade],
        "slide_width": slide_w,
        "slide_height": slide_h,
        "n_patches": n,
        "tumour_patch_fraction": float(tumour_flags_array.mean()),
    }


def generate(out_dir: str | Path, args: argparse.Namespace) -> Dict[str, Any]:
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    rng = np.random.default_rng(args.seed)

    rows: List[Dict[str, Any]] = []
    per_split: Dict[str, Dict[str, int]] = {split: {} for split in SPLIT_COUNTS}
    global_index = 0

    for split, count in SPLIT_COUNTS.items():
        n = getattr(args, f"n_{split}", count)
        for i in range(n):
            grade = i % 6  # cycles 0..5 so every split sees every grade
            image_id = f"mock_{split}_{global_index:04d}"
            global_index += 1
            record = _make_slide(
                out_dir=out_dir,
                image_id=image_id,
                grade=grade,
                rng=rng,
                feature_dim=args.feature_dim,
                grid_cols=args.grid_cols,
                grid_rows=args.grid_rows,
                patch_size=args.patch_size,
                thumbnail_width=args.thumbnail_width,
                patch_px=args.patch_px,
                tissue_fraction_target=args.tissue_fraction,
                signal_strength=args.signal_strength,
                nuisance_strength=args.nuisance_strength,
            )
            record["split"] = split
            rows.append(record)
            per_split[split][grade] = per_split[split].get(grade, 0) + 1

    manifest_path = out_dir / "manifest.csv"
    fieldnames = ["image_id", "data_provider", "isup_grade", "gleason_score", "split"]
    with manifest_path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=fieldnames)
        writer.writeheader()
        for row in rows:
            writer.writerow({key: row[key] for key in fieldnames})

    summary = {
        "synthetic": True,
        "warning": "SYNTHETIC MOCK DATA -- for pipeline debugging only, never reportable.",
        "seed": args.seed,
        "feature_dim": args.feature_dim,
        "grid": [args.grid_cols, args.grid_rows],
        "patch_size": args.patch_size,
        "counts_per_split": {split: len([r for r in rows if r["split"] == split]) for split in SPLIT_COUNTS},
        "class_distribution": {split: {str(g): c for g, c in sorted(d.items())} for split, d in per_split.items()},
        "slides": rows,
    }
    (out_dir / "generator_config.json").write_text(json.dumps(summary, indent=2), encoding="utf-8")
    (out_dir / "README.md").write_text(DISCLAIMER, encoding="utf-8")
    return summary


def main(argv: List[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate SYNTHETIC PANDA-shaped mock data.")
    parser.add_argument("--out-dir", default="data/mock")
    parser.add_argument("--n-train", type=int, default=SPLIT_COUNTS["train"])
    parser.add_argument("--n-val", type=int, default=SPLIT_COUNTS["val"])
    parser.add_argument("--n-test", type=int, default=SPLIT_COUNTS["test"])
    parser.add_argument("--feature-dim", type=int, default=1024)
    parser.add_argument("--grid-cols", type=int, default=8)
    parser.add_argument("--grid-rows", type=int, default=8)
    parser.add_argument("--patch-size", type=int, default=256)
    parser.add_argument("--patch-px", type=int, default=64, help="saved tile resolution")
    parser.add_argument("--thumbnail-width", type=int, default=384)
    parser.add_argument("--tissue-fraction", type=float, default=0.85)

    parser.add_argument("--signal-strength", type=float, default=4.0)
    parser.add_argument(
        "--nuisance-strength", type=float, default=2.5,
        help="shared per-slide offset that forces attention pooling to be useful",
    )
    parser.add_argument("--seed", type=int, default=7)
    args = parser.parse_args(argv)

    summary = generate(args.out_dir, args)
    total = sum(summary["counts_per_split"].values())
    print(f"Generated {total} SYNTHETIC slides -> {args.out_dir}")
    print(f"  manifest: {Path(args.out_dir) / 'manifest.csv'}")
    print(f"  features: {Path(args.out_dir) / 'features'} (dim={args.feature_dim})")
    print("  NOTE: synthetic data -- metrics from it are NOT reportable.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
